"""Turn the logged benchmark results into the figures and tables of the report.

    python evaluation/make_figures.py            (needs matplotlib: pip install -e ".[eval]")

Reads results/{manipulation,manipulation_physics,perception,perception_scenarios,prediction,prediction_physics,
command,command_fast,command_physics,scenario_matrix,clearing}.csv, written by the benchmark scripts
in this directory, and writes evaluation/figures/*.png and evaluation/figures/tables.md. A missing CSV is skipped.
"""
import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

parser = argparse.ArgumentParser()
parser.add_argument("--results", type=Path, default=Path("results"))
parser.add_argument("--out", type=Path, default=Path(__file__).parent / "figures")
args = parser.parse_args()
args.out.mkdir(parents=True, exist_ok=True)

MODE_COLORS = {"single": "tab:gray", "fixed": "tab:blue", "coordinated": "tab:green"}
DETECTOR_COLORS = {"HSV": "tab:orange", "YOLO": "tab:blue", "YOLO + MobileSAM": "tab:green", "YOLO + SAM-B": "tab:red"}
tables: list[str] = ["# Result tables", "", "Generated by `evaluation/make_figures.py` from the CSV files in `results/`. Do not edit.", ""]


def read(name: str) -> list[dict]:
    path = args.results / name
    if not path.exists():
        print(f"skipped: {path} not found")
        return []
    with path.open() as f:
        return list(csv.DictReader(f))


def table(title: str, header: list[str], rows: list[list[str]]) -> None:
    tables.extend([f"## {title}", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)])
    tables.extend("| " + " | ".join(row) + " |" for row in rows)
    tables.append("")


def save(figure, name: str) -> None:
    figure.tight_layout()
    figure.savefig(args.out / name, dpi=150)
    plt.close(figure)
    print(f"wrote {args.out / name}")


def share(runs: list[dict], key: str) -> float:
    return sum(float(r[key]) for r in runs) / sum(float(r["boxes"]) for r in runs)


# ---------------------------------------------------------------- manipulation: three configurations
runs = read("manipulation.csv")
if runs:
    plain = [r for r in runs if float(r["blocked_pairs"]) == 0]
    paired = [r for r in runs if float(r["blocked_pairs"]) > 0]
    modes = list(MODE_COLORS)

    def colors_of(run: dict) -> str:
        weights = json.loads(run["color_weights"])
        return "gray-heavy" if weights["gray"] > 1 else "green-heavy" if weights["green"] > 1 else "uniform"

    factors = [("belt speed [m/s]", lambda r: r["speed"]), ("box spacing [m]", lambda r: r["spacing"]),
               ("number of boxes", lambda r: str(int(float(r["boxes"])) // 10 * 10)), ("color distribution", colors_of)]
    figure, axes = plt.subplots(1, len(factors), figsize=(4 * len(factors), 3.6), sharey=True)
    rows = [["all streams"] + [f"{share([r for r in plain if r['mode'] == m], 'sorted_correctly'):.1%}" for m in modes]]
    for axis, (label, key) in zip(axes, factors):
        groups = defaultdict(list)
        for r in plain:
            groups[key(r)].append(r)
        levels = sorted(groups)
        for i, mode in enumerate(modes):
            values = [share([r for r in groups[level] if r["mode"] == mode], "sorted_correctly") for level in levels]
            axis.bar(np.arange(len(levels)) + (i - 1) * 0.27, values, 0.27, color=MODE_COLORS[mode], label=mode)
        for level in levels:
            rows.append([f"{label.split(' [')[0]} {level}"] + [
                f"{share([r for r in groups[level] if r['mode'] == m], 'sorted_correctly'):.1%}" for m in modes])
        axis.set_xticks(np.arange(len(levels)), levels)
        axis.set_xlabel(label)
        axis.grid(axis="y", alpha=0.3)
    axes[0].set_ylabel("share of boxes sorted correctly")
    axes[0].set_ylim(0, 1)
    axes[0].legend(fontsize=8)
    save(figure, "manipulation_sorted.png")
    table(f"Manipulation: share of boxes sorted correctly ({len(plain) // 3} streams per configuration)", ["streams"] + modes, rows)

    def mean(mode_runs: list[dict], key: str) -> float:
        return float(np.nanmean([float(r[key]) for r in mode_runs]))

    by_mode = {m: [r for r in plain if r["mode"] == m] for m in modes}
    metrics = [("sorted correctly", lambda rs: f"{share(rs, 'sorted_correctly'):.1%}"),
               ("left the belt", lambda rs: f"{share(rs, 'missed'):.1%}"),
               ("grasp success rate", lambda rs: f"{mean(rs, 'grasp_success_rate'):.2f}"),
               ("sorting accuracy", lambda rs: f"{mean(rs, 'sorting_accuracy'):.2f}"),
               ("throughput [boxes/min]", lambda rs: f"{mean(rs, 'throughput'):.2f}"),
               ("planning time per pick-and-place, mean [s]", lambda rs: f"{mean(rs, 'planning_time_mean'):.2f}"),
               ("planning time, worst run [s]", lambda rs: f"{max(float(r['planning_time_max']) for r in rs):.2f}"),
               ("completion time, mean [s]", lambda rs: f"{mean(rs, 'completion_time'):.0f}"),
               ("shared-area conflicts per run", lambda rs: f"{mean(rs, 'conflicts'):.2f}"),
               ("waiting time per run [s]", lambda rs: f"{mean(rs, 'waiting_time'):.2f}")]
    table("Manipulation: all metrics per configuration", ["metric"] + modes,
          [[name] + [value(by_mode[m]) for m in modes] for name, value in metrics])
    if paired:
        rows = []
        for mode in modes:
            rs = [r for r in paired if r["mode"] == mode]
            attempts = sum(int(r["clear_and_sort_attempts"]) for r in rs)
            successes = sum(round(float(r["clear_and_sort_success_rate"]) * int(r["clear_and_sort_attempts"]))
                            for r in rs if int(r["clear_and_sort_attempts"]))
            rows.append([mode, f"{share(rs, 'sorted_correctly'):.1%}", str(sum(int(r["blocked_pairs_spawned"]) for r in rs)),
                         str(attempts), f"{successes / attempts:.0%}" if attempts else "-"])
        table(f"Manipulation: streams with blocked pairs ({len(paired) // 3} streams per configuration)",
              ["configuration", "sorted correctly", "blocked pairs", "clear-and-sort attempts", "success rate"], rows)

# ---------------------------------------------------------------- manipulation: kinematic vs physics (#107)
physical = read("manipulation_physics.csv")
if runs and physical:
    def numbers(rs: list[dict], key: str) -> list[float]:
        return [float(r[key]) for r in rs if r.get(key, "") not in ("", "nan")]

    def column(rs: list[dict]) -> dict[str, str]:
        total = sum(float(r["boxes"]) for r in rs)
        values = {"sorted correctly": f"{share(rs, 'sorted_correctly'):.1%}", "left the belt": f"{share(rs, 'missed'):.1%}",
                  "grasp success rate": f"{np.mean(numbers(rs, 'grasp_success_rate')):.2f}",
                  "throughput [boxes/min]": f"{np.mean(numbers(rs, 'throughput')):.2f}",
                  "planning time per pick-and-place, mean [s]": f"{np.mean(numbers(rs, 'planning_time_mean')):.2f}",
                  "completion time, mean [s]": f"{np.mean(numbers(rs, 'completion_time')):.0f}"}
        if "slips" in rs[0]:   # physics runs only
            failures = {k: int(sum(numbers(rs, k))) for k in ("grasp_failures", "slips", "drops", "other_failures")}
            values |= {"grasp failures / slips / drops / other": "{grasp_failures} / {slips} / {drops} / {other_failures}".format(**failures),
                       "failed attempts per 100 boxes": f"{100 * sum(failures.values()) / total:.1f}",
                       "arm contacts": str(int(sum(numbers(rs, "arm_contacts")))),
                       "closest arm approach [cm]": f"{100 * min(numbers(rs, 'min_arm_distance')):.1f}"}
        return values

    rows, header = defaultdict(list), ["metric"]
    for mode in MODE_COLORS:
        for backend, rs in (("kinematic", runs), ("physics", physical)):
            selected = [r for r in rs if r["mode"] == mode and float(r["blocked_pairs"]) == 0]
            if not selected:
                continue
            values = column(selected)
            header.append(f"{mode}, {backend}")
            for name in ("sorted correctly", "left the belt", "grasp success rate", "throughput [boxes/min]",
                         "planning time per pick-and-place, mean [s]", "completion time, mean [s]",
                         "grasp failures / slips / drops / other", "failed attempts per 100 boxes", "arm contacts",
                         "closest arm approach [cm]"):
                rows[name].append(values.get(name, "-"))
    table(f"Manipulation: kinematic vs physics ({len([r for r in physical if float(r['blocked_pairs']) == 0]) // 3} "
          "streams per configuration, ground-truth detections)", header, [[name] + cells for name, cells in rows.items()])

# ---------------------------------------------------------------- perception: HSV vs YOLO vs SAM
def partly_hidden(row: dict) -> str:
    """Boxes a third to two thirds visible (#110): found / counted; '-' for none or for an older CSV."""
    n = int(float(row.get("partly_hidden") or 0))
    return f"{round(float(row['partly_hidden_recall']) * n)} of {n}" if n else "-"


rows_csv = read("perception.csv")
if rows_csv:
    conditions = list(dict.fromkeys(r["condition"] for r in rows_csv))
    detectors = list(dict.fromkeys(r["detector"] for r in rows_csv))
    cell = {(r["condition"], r["detector"]): r for r in rows_csv}
    figure, axes = plt.subplots(1, 3, figsize=(14, 3.8))
    panels = [("recall", "recall (boxes found with the right color)", (0.85, 1.005)),
              ("error_mean_mm", "mean position error [mm]", None), ("time_ms", "time per frame [ms]", None)]
    for axis, (key, label, limits) in zip(axes, panels):
        for i, detector in enumerate(detectors):
            values = [float(cell[c, detector][key]) for c in conditions]
            axis.bar(np.arange(len(conditions)) + (i - 1.5) * 0.2, values, 0.2, color=DETECTOR_COLORS.get(detector), label=detector)
        axis.set_xticks(np.arange(len(conditions)), [c.split(" (")[0] for c in conditions])
        axis.set_ylabel(label)
        axis.grid(axis="y", alpha=0.3)
        if limits:
            axis.set_ylim(*limits)
    axes[2].set_yscale("log")
    figure.legend(*axes[0].get_legend_handles_labels(), ncol=len(detectors), fontsize=8, loc="upper center")
    figure.tight_layout(rect=(0, 0, 1, 0.93))
    figure.savefig(args.out / "perception.png", dpi=150)
    plt.close(figure)
    print(f"wrote {args.out / 'perception.png'}")
    table("Perception: detectors on the same scenes", ["condition", "detector", "boxes", "recall", "wrong color", "precision",
                                                       "error mean / max [mm]", "mask IoU", "partly hidden: found",
                                                       "time [ms]"],
          [[c if d == detectors[0] else "", d, cell[c, d]["boxes"], f"{float(cell[c, d]['recall']):.3f}",
            f"{float(cell[c, d]['wrong_color']):.3f}", f"{float(cell[c, d]['precision']):.3f}",
            f"{float(cell[c, d]['error_mean_mm']):.1f} / {float(cell[c, d]['error_max_mm']):.1f}",
            "-" if cell[c, d]["mask_iou"] == "nan" else f"{float(cell[c, d]['mask_iou']):.3f}", partly_hidden(cell[c, d]),
            f"{float(cell[c, d]['time_ms']):.0f}"]
           for c in conditions for d in detectors])

# ---------------------------------------------------------------- perception: dense and occluded BotOp scenarios (#103, #110)
rows_csv = read("perception_scenarios.csv")
if rows_csv:
    layout_rows = [r for r in rows_csv if r["case"] == "layout"]
    if layout_rows:
        groups = defaultdict(list)
        for r in layout_rows:
            groups[(r["layout"], r["spacing"], r["detector"])].append(r)
        summary_rows = []
        for (layout, spacing, detector), rs in groups.items():
            boxes = sum(int(float(r["boxes"])) for r in rs)
            recall = sum(float(r["recall"]) * float(r["boxes"]) for r in rs) / boxes if boxes else np.nan
            wrong = sum(float(r["wrong_color"]) * float(r["boxes"]) for r in rs) / boxes if boxes else np.nan
            errs = [float(r["error_mean_mm"]) for r in rs if r.get("error_mean_mm", "") not in ("", "nan")]
            err_str = f"{np.mean(errs):.1f}" if errs else "-"
            summary_rows.append([layout, spacing, detector, str(boxes), f"{recall:.1%}" if boxes else "-",
                                 f"{wrong:.1%}" if boxes else "-", err_str])
        table("Perception on BotOp images: dense and occluded layouts",
              ["layout", "spacing", "detector", "boxes", "recall", "wrong color", "error mean [mm]"], summary_rows)

    cover_rows = [r for r in rows_csv if r["case"] == "cover"]
    if cover_rows:
        covers = list(dict.fromkeys(r["cover"] for r in cover_rows))
        detectors = list(dict.fromkeys(r["detector"] for r in cover_rows))
        by_cover = {(r["cover"], r["detector"]): r for r in cover_rows}
        cover_table = []
        for cover in covers:
            visible = next((by_cover[cover, d]["visible"] for d in detectors if (cover, d) in by_cover), "")
            vis_str = f"{float(visible):.0%}" if visible not in ("", "nan") else "-"
            cells = []
            for d in detectors:
                r = by_cover.get((cover, d))
                if not r:
                    cells.append("-")
                elif r["found"] == "True":
                    cells.append("found")
                elif r["wrong_color"] == "True":
                    cells.append("wrong color")
                else:
                    cells.append("-")
            cover_table.append([cover, vis_str] + cells)
        table("Perception on BotOp images: target partly covered by an arm",
              ["cover (height / offset [m])", "visible"] + detectors, cover_table)

# ---------------------------------------------------------------- prediction: constant-velocity fit vs Kalman
rows_csv = read("prediction.csv")
if rows_csv:
    names = {"cv": "constant-velocity fit (window 20)", "kalman": "Kalman filter"}
    frames = sorted({int(r["frames"]) for r in rows_csv})
    noises = sorted({float(r["noise_mm"]) for r in rows_csv})
    figure, axes = plt.subplots(1, len(frames), figsize=(4.5 * len(frames), 3.8), sharey=True)
    for axis, n in zip(axes, frames):
        for predictor, style in (("cv", "o-"), ("kalman", "s--")):
            for noise, color in zip(noises, ("tab:gray", "tab:blue", "tab:red")):
                points = sorted((float(r["horizon_s"]), float(r["mean_error_mm"])) for r in rows_csv
                                if r["predictor"] == predictor and int(r["frames"]) == n and float(r["noise_mm"]) == noise)
                axis.plot(*zip(*points), style, color=color, markersize=4, label=f"{names[predictor]}, noise {noise:.0f} mm")
        axis.set_title(f"{n} detections ({n / 20:.0f} s of tracking)")
        axis.set_xlabel("prediction horizon [s]")
        axis.grid(alpha=0.3)
    axes[0].set_ylabel("mean position error [mm]")
    axes[0].legend(fontsize=7)
    save(figure, "prediction_error.png")
    value = {(r["predictor"], float(r["noise_mm"]), int(r["frames"]), float(r["horizon_s"])): r for r in rows_csv}
    table("Prediction: mean position error [mm] 3 s ahead, fit / Kalman", ["detection noise"] + [f"{n} detections" for n in frames],
          [[f"{noise:.0f} mm"] + [f"{float(value['cv', noise, n, 3.0]['mean_error_mm']):.2f} / "
                                  f"{float(value['kalman', noise, n, 3.0]['mean_error_mm']):.2f}" for n in frames] for noise in noises])

rows_csv = read("prediction_physics.csv")
if rows_csv:
    horizons = sorted({float(r["horizon_s"]) for r in rows_csv})
    value = {(r["detector"], r["predictor"], float(r["horizon_s"])): r for r in rows_csv}
    detectors = list(dict.fromkeys(r["detector"] for r in rows_csv))
    table(f"Prediction on the physical belt ({rows_csv[0]['speed']} m/s): mean position error [mm], fit / Kalman",
          ["detector", "step mean / max [s]"] + [f"{h:g} s ahead" for h in horizons],
          [[d, f"{float(value[d, 'cv', horizons[0]]['step_mean_s']):.3f} / {float(value[d, 'cv', horizons[0]]['step_max_s']):.3f}"]
           + [f"{float(value[d, 'cv', h]['mean_error_mm']):.2f} / {float(value[d, 'kalman', h]['mean_error_mm']):.2f}" for h in horizons]
           for d in detectors])

# ---------------------------------------------------------------- command mode
rows = []
for name, label in (("command.csv", "0.1 m/s, a box every 4 s"), ("command_fast.csv", "0.2 m/s, a box every 2 s")):
    records = read(name)
    if records:
        n = len(records)
        correct = [r for r in records if r["correct_color"] == "True" and r["correct_region"] == "True"]
        times = [float(r["time"]) for r in correct]
        rows.append([label, str(n), str(sum(r["parsed"] == "True" for r in records)),
                     str(sum(r["correct_color"] == "True" for r in records)),
                     str(sum(r["correct_region"] == "True" for r in records)), f"{len(correct) / n:.0%}",
                     f"{np.mean(times):.1f} / {np.max(times):.1f}",
                     f"{sum(r['robot'] == '1' for r in records)} / {sum(r['robot'] == '2' for r in records)}"])
if rows:
    table("Command mode: random commands", ["belt", "commands", "parsed", "correct color", "correct destination", "success rate",
                                            "time mean / max [s]", "Robot 1 / Robot 2"], rows)

# ---------------------------------------------------------------- command mode on physics (#109)
records = read("command_physics.csv")
if records:
    rows = []
    for speed, blocked in sorted({(r["speed"], r["blocked_pairs"]) for r in records}, key=lambda k: (float(k[1]), float(k[0]))):
        rs = [r for r in records if (r["speed"], r["blocked_pairs"]) == (speed, blocked)]
        correct = [r for r in rs if r["correct_color"] == "True" and r["correct_region"] == "True"]
        times = [float(r["time"]) for r in correct]
        failures = defaultdict(int)
        for r in rs:
            if r not in correct:
                failures[r["failed_stage"]] += 1
        rows.append([f"{speed} m/s", "every box blocked" if float(blocked) else "normal", str(len(rs)),
                     f"{len(correct) / len(rs):.0%}", f"{np.mean(times):.1f} / {np.max(times):.1f}" if times else "-",
                     ", ".join(f"{k} {v}" for k, v in sorted(failures.items())) or "-",
                     f"{sum(r['robot'] == '1' for r in rs)} / {sum(r['robot'] == '2' for r in rs)}"])
    table("Command mode on physics: random commands (a box every 0.4 m; blocked: a gray box 8 cm in front of each colored one)",
          ["belt", "stream", "commands", "success rate", "time mean / max [s]", "failures", "Robot 1 / Robot 2"], rows)

# ---------------------------------------------------------------- scenario matrix (#106)
records = read("scenario_matrix.csv")
if records:
    speeds = sorted({float(r["speed"]) for r in records})
    cell = {(r["layout"], r["lateral"], float(r["speed"])): r for r in records}
    rows = []
    for layout, lateral in dict.fromkeys((r["layout"], r["lateral"]) for r in records):
        expectations = list(dict.fromkeys(cell[layout, lateral, v]["expected"] for v in speeds if (layout, lateral, v) in cell))
        row = [layout, lateral.replace("_", " ")]
        for v in speeds:
            r = cell.get((layout, lateral, v))
            row.append("-" if r is None else r["observed"] + ("" if r["ok"] == "True" else " **(unexpected)**"))
        rows.append(row + [" / ".join(expectations)])
    ok = sum(r["ok"] == "True" for r in records)
    table(f"Scenario matrix on physics: observed outcome per cell ({ok} of {len(records)} as expected, "
          f"{sum(int(r['arm_contacts']) for r in records)} arm contacts)",
          ["neighbourhood", "lateral"] + [f"{v:g} m/s" for v in speeds] + ["expected"], rows)

# ---------------------------------------------------------------- blocked and surrounded targets (#108)
records = read("clearing.csv")
if records:
    cells = defaultdict(list)
    for r in records:
        cells[r["layout"], float(r["speed"])].append(r)
    free = {v: np.nanmean([float(r["time"]) for r in rs if r["outcome"] == "sorted"]) for (layout, v), rs in cells.items()
            if layout == "free"}
    rows = []
    for (layout, v), rs in cells.items():
        success = [r for r in rs if r["outcome"] in ("sorted", "cleared")]
        extra = [float(r["time"]) - free[v] for r in success if v in free]
        rate = lambda n: f"{n / len(rs):.0%}"
        rows.append([layout, f"{v:g}", str(len(rs)), rs[0]["expected"], rate(len(success)),
                     rate(sum(r["outcome"] == "infeasible" for r in rs)),
                     rate(sum(r["outcome"] in ("failed", "missed") for r in rs)),
                     f"{np.mean(extra):+.1f}" if extra and layout != "free" else "-",
                     str(sum(int(r["arm_contacts"]) for r in rs))])
    table("Blocked and surrounded targets on physics (runs per cell; extra time: to sort the target, against a free "
          "target at the same speed)",
          ["neighbourhood", "belt [m/s]", "runs", "expected", "sorted", "infeasible reported", "failed or missed",
           "extra time [s]", "arm contacts"], rows)

(args.out / "tables.md").write_text("\n".join(tables), encoding="utf-8")
print(f"wrote {args.out / 'tables.md'}")
